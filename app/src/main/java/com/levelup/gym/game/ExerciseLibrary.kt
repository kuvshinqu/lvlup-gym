enum class Equipment(val label: String) {
    BARBELL("Barbell"), DUMBBELL("Dumbbell"), SMITH("Smith machine"), CABLE("Cable"),
    MACHINE("Machine"), BODYWEIGHT("Bodyweight"), CARDIO("Cardio"),
}

/**
 * One entry of the common exercise list the hero can add from.
 * [longLength] marks moves that load the muscle hard while it is stretched; recent studies
 * (Maeo 2021 and 2023, Pedrosa 2022, Wolf 2023 review) found these tend to grow muscle a bit better.
 */
data class LibraryExercise(
    val name: String,
    val muscleGroup: String,
    val equipment: Equipment,
    val guide: ExerciseGuide? = null,
    val kind: ExerciseKind = ExerciseKind.STRENGTH,
    val longLength: Boolean = false,
)

private fun g(avoid: String, vararg cues: String, bodyweight: Boolean = false, timed: Boolean = false) =
    ExerciseGuide(cues.toList(), avoid, bodyweight = bodyweight, timed = timed)

